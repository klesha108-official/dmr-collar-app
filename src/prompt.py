"""ChatGPT / Gemini に貼る着色指示文を作る。毎回同じ構成にして品質をそろえる。"""

# パーツの初期値（名前, 色の説明）。サンプルのトーンに合わせたパステル
DEFAULT_PARTS = {
    "髪": ("明るい灰茶（アッシュベージュ）", "#C9B29C"),
    "肌": ("やわらかいピーチ", "#F6D5C3"),
    "頬": ("ごく薄いピンク（丸くぼかす）", "#F4B7B5"),
    "目": ("グレーがかった茶", "#8F8C93"),
    "服1": ("淡いデニムブルー", "#B9CFE6"),
    "服2": ("オフホワイト", "#F2EFEA"),
}

SATURATION = ["かなり控えめ", "控えめ", "標準", "やや鮮やか"]
DENSITY = ["かなり淡い", "淡い", "標準", "しっかり"]
TEXTURES = {
    "コピック風（透明感のある重ね塗り）":
        "コピックマーカーのような透明感のある重ね塗り。色の境目に少しムラとにじみ、紙の白が透ける。",
    "水彩風（にじみ）": "水彩のような柔らかいにじみと色の溜まり。",
    "フラット（均一な塗り）": "ムラの少ない均一な塗り。影は控えめ。",
}
BACKGROUNDS = ["無地の紙（白〜オフホワイト）", "ごく薄いグラデーションの紙", "背景は塗らず紙のまま"]


def build_prompt(parts: dict, *, saturation: str, density: str, texture: str, background: str,
                 shading: str = "肌と服に柔らかなグラデーションと影、小さな白ハイライトを入れる", extra: str = "") -> str:
    """parts: {名前: (色の説明, #カラーコード)}"""
    color_lines = "\n".join(f"- {name}: {desc}（目安 {code}）" for name, (desc, code) in parts.items() if desc.strip())
    p = f"""添付の画像は、シャープペンで描いたモノクロの線画です。この線画を、パステル調でデジタル着色してください。

【厳守】
- 線画の構図・ポーズ・線を一切変えないこと（描き直し・追加・削除・移動をしない）。
- 画像のサイズ・縦横比を変えず、トリミングもしないこと。
- 文字・ロゴ・透かし・新しい小物・背景の模様を足さないこと。
- 鉛筆の線は消さずに残すこと。

【塗り方】
- {TEXTURES[texture]}
- {shading}。
- 彩度は{saturation}、塗りの濃さは{density}のパステル調。

【配色】
{color_lines}

【背景】
- {background}。
"""
    if extra.strip():
        p += f"\n【追加指示】\n- {extra.strip()}\n"
    return p
